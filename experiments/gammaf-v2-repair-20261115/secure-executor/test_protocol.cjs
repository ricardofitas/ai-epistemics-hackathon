const assert=require('node:assert/strict'),crypto=require('node:crypto');
const {openEnvelope}=require('./sealed.cjs');
const recipient=crypto.generateKeyPairSync('x25519'),sender=crypto.generateKeyPairSync('x25519');
const pub=recipient.publicKey.export({format:'der',type:'spki'}).toString('base64url');
const context={protocol:'rfdl-gammaf-sealed-v1',repository:'rfitas-lab/rfdl-lab-os',run_id:'123',study:'gammaf-v2-full-options-20261115',commit_sha:'a'.repeat(40),manifest_sha256:'b'.repeat(64),freeze_sha256:'c'.repeat(64),deadline_utc:'2026-11-16T03:00:00Z'};
