'use strict';
const crypto=require('node:crypto'),fs=require('node:fs'),path=require('node:path');
const root=path.resolve(__dirname,'..');
const config=JSON.parse(fs.readFileSync(path.join(root,'executor-config.json'),'utf8'));
const repo=process.env.GITHUB_REPOSITORY,runId=process.env.GITHUB_RUN_ID,sha=process.env.GITHUB_SHA;
if(repo!=='rfitas-lab/rfdl-lab-os'||!runId||!sha||config.study!=='gammaf-v2-full-options-20261115')throw new Error('Unexpected executor context');
const plan=fs.readFileSync(path.join(root,config.plan_path));
const digest=crypto.createHash('sha256').update(plan).digest('hex');
if(digest!==config.plan_sha256)throw new Error('Plan digest mismatch');
const freeze=fs.readFileSync(path.join(root,'FREEZE.json'));
const freezeSha=crypto.createHash('sha256').update(freeze).digest('hex');
if(!Number.isFinite(Date.parse(config.deadline_utc))||Date.now()>=Date.parse(config.deadline_utc))throw new Error('Inference deadline reached before credential exchange');
const pair=crypto.generateKeyPairSync('x25519');
const pub=pair.publicKey.export({format:'der',type:'spki'}).toString('base64url');
const privatePath=path.join(process.env.RUNNER_TEMP,'gammaf-ephemeral-'+runId+'.pem');
fs.writeFileSync(privatePath,pair.privateKey.export({format:'pem',type:'pkcs8'}),{flag:'wx',mode:0o600});
const context={protocol:'rfdl-gammaf-sealed-v1',repository:repo,run_id:String(runId),study:config.study,commit_sha:sha,manifest_sha256:digest,freeze_sha256:freezeSha,deadline_utc:config.deadline_utc};
const out=path.join(root,'credential-public.json');
fs.writeFileSync(out,JSON.stringify({public_spki_b64url:pub,context},null,2)+'\n');
const artifact='gammaf-key-'+runId+'-'+pub;
fs.appendFileSync(process.env.GITHUB_OUTPUT,'artifact_name='+artifact+'\n');
console.log(JSON.stringify({credential_exchange:'public_key_ready',study:config.study,run_id:runId,provider_calls:0,manifest_sha256:digest}));
